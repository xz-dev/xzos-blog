export type PixelIconName = keyof typeof PIXEL_ICONS;
export type PixelRect = { x: number; y: number; width: number; height: number };

export function pixelIconRects(name: PixelIconName): PixelRect[] {
	return PIXEL_ICONS[name].flatMap((row, y) => [...row.matchAll(/#+/g)].map((run) => ({
		x: run.index,
		y,
		width: run[0].length,
		height: 1,
	})));
}

/** Static favicon serializer; page SVGs use the same rectangles in PixelIcon. */
export function renderPixelIconSvg(name: PixelIconName, color = 'currentColor'): string {
	if (!/^(?:currentColor|#[0-9a-fA-F]{6})$/.test(color)) throw new Error('Invalid pixel icon color');
	const rects = pixelIconRects(name).map(({ x, y, width, height }) =>
		`<rect x="${x}" y="${y}" width="${width}" height="${height}"/>`,
	).join('');
	return `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" color="${color}" fill="currentColor" shape-rendering="crispEdges">${rects}</svg>`;
}

type ArrowPart = { text: string; icon?: 'arrow-left' | 'arrow-right' };

/** Preserve the localized label byte-for-byte; replace only the two UI arrows. */
export function splitPixelArrowText(text: string): ArrowPart[] {
	return text.split(/([←→])/).filter(Boolean).map((part) => ({
		text: part,
		icon: part === '←' ? 'arrow-left' : part === '→' ? 'arrow-right' : undefined,
	}));
}
